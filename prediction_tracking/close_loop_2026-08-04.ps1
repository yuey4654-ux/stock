function Add-UniqueRows([string]$Path,[object[]]$NewRows){
  $rows=@(Import-Csv $Path -Encoding UTF8)
  foreach($n in $NewRows){if(@($rows|Where-Object{$_.'目标日期' -eq $n.'目标日期' -and $_.'市场' -eq $n.'市场' -and $_.'代码' -eq $n.'代码'}).Count -eq 0){$rows+=$n}}
  $rows|Export-Csv $Path -NoTypeInformation -Encoding UTF8
}
