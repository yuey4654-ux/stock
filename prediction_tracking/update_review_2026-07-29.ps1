function Upsert-Summary {
    param(
        [string]$CsvName,
        [string]$MdName,
        [bool]$RuleOnly
    )
    $csvPath = Join-Path $tracking $CsvName
    $summary = @(Import-Csv -LiteralPath $csvPath | Where-Object { $_.'目标日期' -ne '2026-07-29' })
    $next = [ordered]@{
        '目标日期' = '2026-07-29'
        '预测日期' = '2026-07-28'
        '总数' = $(if ($RuleOnly) { '1' } else { '3' })
        '命中' = '0'
        '部分命中' = $(if ($RuleOnly) { '1' } else { '3' })
        '未命中' = '0'
        '严格命中率' = '0.0%'
        '调整后命中率' = '50.0%'
        '严格加权命中率' = '0.0%'
        '调整后加权命中率' = '50.0%'
        '核心承接命中' = '0'
        '核心承接总数' = '0'
        '稳健观察命中' = '0'
        '稳健观察总数' = '1'
        '弹性进攻命中' = '0'
        '弹性进攻总数' = '0'
        '其他类型命中' = '0'
        '其他类型总数' = $(if ($RuleOnly) { '0' } else { '2' })
        '最佳预测' = $(if ($RuleOnly) { '伊利股份' } else { '伊利股份; 建设银行; 工商银行' })
        '最差预测' = '无'
        '主要误差' = $(if ($RuleOnly) {
            '伊利股份方向和尾盘强度正确，但全天最低26.72，未进入26.20-26.40计划回踩区；正式规则再次出现收盘走强但买点不可执行。'
        } else {
            '伊利股份未给计划买点；建设银行、工商银行虽触及承接区，但尾盘分别未站回10.66和7.96确认位。三票方向与承接尚可，执行条件均不完整。'
        })
        $(if ($RuleOnly) { '规则调整信号' } else { '策略提醒' }) = '是'
        '下一步规则调整' = '触发原因：唯一正式规则票伊利股份仅部分命中，规则票严格命中率0%、调整后加权命中率50%，低于60%/65%阈值。建议：下一交易日正式规则票维持0-1只，继续优先低波动稳健观察；不得因尾盘走强放宽计划买点，消费与银行都必须完成回踩和尾盘确认。适用范围：A股正式规则票及防守型条件观察票。失效条件：连续两日规则票调整后加权命中率高于65%，且无买点缺失、盘中失效或冲高回落样本。'
        '报告文件' = $reportRel
    }
    $summary += [pscustomobject]$next
    $summary = @($summary | Sort-Object { [datetime]$_.'目标日期' })
    $summary | Export-Csv -LiteralPath $csvPath -NoTypeInformation -Encoding UTF8

    $headers = @($summary[0].PSObject.Properties.Name)
    $lines = @(
        "# 每日预测复盘汇总",
        "",
        "| " + ($headers -join ' | ') + " |",
        "| " + (($headers | ForEach-Object { '---' }) -join ' | ') + " |"
    )
    foreach ($item in $summary) {
        $vals = foreach ($header in $headers) {
            ([string]$item.$header).Replace('|', '\|').Replace("`r", ' ').Replace("`n", ' ')
        }
        $lines += "| " + ($vals -join ' | ') + " |"
    }
    Set-Content -LiteralPath (Join-Path $tracking $MdName) -Value $lines -Encoding UTF8
}

