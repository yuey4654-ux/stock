function Add-UniqueRows {
    param([string]$Path, [array]$NewRows)
    $rows = @(Import-Csv -LiteralPath $Path)
    foreach ($newRow in $NewRows) {
        $exists = $rows | Where-Object {
            $_.'目标日期' -eq $newRow.'目标日期' -and
            $_.'市场' -eq $newRow.'市场' -and
            $_.'代码' -eq $newRow.'代码'
        }
        if (-not $exists) { $rows += [pscustomobject]$newRow }
    }
    $rows | Export-Csv -LiteralPath $Path -NoTypeInformation -Encoding UTF8
}

