def review_file(name, reviews):
    p = PT / name
    df = pd.read_csv(p, dtype=str, encoding="utf-8-sig").fillna("")
    mask = (df["目标日期"] == DATE) & (df["复盘结果"] == "待复盘")
    for idx in df.index[mask]:
        code = df.at[idx, "代码"]
        vals = reviews[code]
        for col, val in zip(["收盘价", "涨跌幅", "是否触发", "是否失效", "复盘结果", "复盘备注"], vals):
            df.at[idx, col] = val
    df.to_csv(p, index=False, encoding="utf-8-sig")
    return df

def rate(v):
    return f"{v:.1f}%"

def summary_row(df, report_file, error, next_adj, signal_col, signal="否"):
    day = df[df["目标日期"] == DATE].copy()
    total = len(day); hit = (day["复盘结果"] == "命中").sum(); part = (day["复盘结果"] == "部分命中").sum(); miss = (day["复盘结果"] == "未命中").sum()
    strict = 100 * hit / total if total else 0
    adjusted = 100 * (hit + 0.5 * part) / total if total else 0
    best = "; ".join(day.loc[day["复盘结果"] == "命中", "名称"]) or "无"
    worst = "; ".join(day.loc[day["复盘结果"] == "未命中", "名称"]) or "无"
    return {"目标日期":DATE,"预测日期":PRED_DATE,"总数":str(total),"命中":str(hit),"部分命中":str(part),"未命中":str(miss),
            "严格命中率":rate(strict),"调整后命中率":rate(adjusted),"严格加权命中率":rate(strict),"调整后加权命中率":rate(adjusted),
            "核心承接命中":"0","核心承接总数":"0","稳健观察命中":"0","稳健观察总数":"0","弹性进攻命中":"0","弹性进攻总数":"0",
            "其他类型命中":str(hit),"其他类型总数":str(total),"最佳预测":best,"最差预测":worst,"主要误差":error,signal_col:signal,"下一步规则调整":next_adj,"报告文件":report_file}

def upsert_summary(path, row):
    df = pd.read_csv(path, dtype=str, encoding="utf-8-sig").fillna("")
    df = df[df["目标日期"] != DATE]
    df = pd.concat([df, pd.DataFrame([row], columns=df.columns)], ignore_index=True).sort_values("目标日期")
    df.to_csv(path, index=False, encoding="utf-8-sig")
    md = path.with_suffix(".md")
    md.write_text("# 每日预测复盘汇总\n\n" + df.to_markdown(index=False) + "\n", encoding="utf-8")

