function Add-PredictionRows {
    param(
        [string]$Path,
        [array]$Rows,
        [string]$TargetDate
    )

    $existing = @(Import-Csv -LiteralPath $Path)
    if (@($existing | Where-Object { $_.'目标日期' -eq $TargetDate }).Count -gt 0) {
        throw "$Path 已存在目标日期 $TargetDate 的记录，停止写入以免覆盖。"
    }

    @($existing + $Rows) | Export-Csv -LiteralPath $Path -NoTypeInformation -Encoding utf8
}

