function Add-UniqueRows {
    param([string]$Path, [object[]]$NewRows)
    $rows = @(Import-Csv -LiteralPath $Path -Encoding UTF8)
    foreach ($new in $NewRows) {
        $dup = @($rows | Where-Object { $_.'目标日期' -eq $new.'目标日期' -and $_.'市场' -eq $new.'市场' -and $_.'代码' -eq $new.'代码' })
        if ($dup.Count -eq 0) { $rows += $new }
    }
    $rows | Export-Csv -LiteralPath $Path -NoTypeInformation -Encoding UTF8
}

